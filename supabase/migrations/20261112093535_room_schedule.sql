-- TODO-18: Room schedule table and room_status SQL function.

create table public.room_schedule (
  id bigint generated by default as identity primary key,
  room_id text not null references public.rooms (id) on delete cascade,
  day smallint not null check (day between 1 and 7),
  start_time time not null,
  end_time time not null,
  subject text not null,
  group_name text not null,
  parity text not null default 'all' check (parity in ('all', 'odd', 'even')),
  constraint room_schedule_time_order check (start_time < end_time)
);

create index room_schedule_room_day_idx on public.room_schedule (room_id, day, start_time);

alter table public.room_schedule enable row level security;

-- Read-only access for authenticated users; no write policies exist for client roles.
create policy "Authenticated users can read room_schedule"
  on public.room_schedule
  for select
  to authenticated
  using (true);

-- Computes whether a room is free or occupied at `p_at`, evaluated in Europe/Bucharest.
-- Mirrors `computeStatus` in `apps/web/features/rooms/server/status.ts`:
--   - unknown room -> ('unknown', null)
--   - end_time is exclusive
--   - back-to-back or overlapping classes are merged into one occupied chain
-- Note: `parity` (odd/even weeks) and teaching period dates are not filtered here yet;
-- they will be connected with TODO-19 in the next stage.
create or replace function public.room_status(
  p_room_id text,
  p_at timestamptz
)
returns table (
  status text,
  until text
)
language plpgsql
stable
as $$
declare
  v_local timestamp;
  v_day smallint;
  v_time time;
  v_until time;
  v_next_until time;
  v_next_start time;
begin
  if not exists (select 1 from public.rooms r where r.id = p_room_id) then
    return query select 'unknown'::text, null::text;
    return;
  end if;

  v_local := p_at at time zone 'Europe/Bucharest';
  v_day := extract(isodow from v_local)::smallint;
  v_time := date_trunc('minute', v_local)::time;

  select max(rs.end_time)
  into v_until
  from public.room_schedule rs
  where rs.room_id = p_room_id
    and rs.day = v_day
    and rs.start_time <= v_time
    and v_time < rs.end_time;

  if v_until is not null then
    loop
      select max(rs.end_time)
      into v_next_until
      from public.room_schedule rs
      where rs.room_id = p_room_id
        and rs.day = v_day
        and rs.start_time <= v_until
        and rs.end_time > v_until;

      exit when v_next_until is null;
      v_until := v_next_until;
    end loop;

    return query select 'occupied'::text, to_char(v_until, 'HH24:MI');
    return;
  end if;

  select min(rs.start_time)
  into v_next_start
  from public.room_schedule rs
  where rs.room_id = p_room_id
    and rs.day = v_day
    and rs.start_time > v_time;

  if v_next_start is not null then
    return query select 'free'::text, to_char(v_next_start, 'HH24:MI');
  else
    return query select 'free'::text, null::text;
  end if;
end;
$$;
