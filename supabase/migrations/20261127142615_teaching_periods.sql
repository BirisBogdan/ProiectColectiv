-- TODO-30: teaching periods, teaching weeks and a room_status that knows about them.
-- Same rules as apps/web/features/rooms/server/calendar.ts and status.ts (TODO-19), so the
-- database gives the same status as TypeScript when the app moves to Supabase (TODO-31).

create table public.teaching_periods (
  id bigint generated by default as identity primary key,
  -- Dates in Europe/Bucharest, both ends included.
  start_date date not null,
  end_date date not null,
  constraint teaching_periods_date_order check (start_date <= end_date)
);

comment on table public.teaching_periods is
  'Semester teaching periods. Outside them (holidays, exam sessions) room status is unknown. '
  'The seed holds the demo periods of apps/web/features/rooms/data/calendar.ts, not the '
  'official academic calendar.';

alter table public.teaching_periods enable row level security;

-- Read-only access for authenticated users; no write policies exist for client roles.
create policy "Authenticated users can read teaching_periods"
  on public.teaching_periods
  for select
  to authenticated
  using (true);

-- The teaching week of p_at: 1, 2, 3, ... or null outside the teaching periods.
-- Mirrors teachingWeek in calendar.ts:
--   - the date is the calendar date in Europe/Bucharest, not the UTC date;
--   - weeks start on Monday, and week 1 is the week of the first period's start date;
--   - the count keeps going through the holidays instead of restarting (calendar weeks),
--     so the parity never shifts. Assumption still to confirm with the faculty (TODO-12).
create or replace function public.teaching_week(p_at timestamptz)
returns integer
language sql
stable
set search_path = ''
as $$
  with local_day as (
    select (p_at at time zone 'Europe/Bucharest')::date as d
  ),
  first_monday as (
    select min(tp.start_date) - (extract(isodow from min(tp.start_date))::int - 1) as m
    from public.teaching_periods tp
  )
  select ((ld.d - (extract(isodow from ld.d)::int - 1)) - fm.m) / 7 + 1
  from local_day ld, first_monday fm
  where exists (
    select 1
    from public.teaching_periods tp
    where tp.start_date <= ld.d and ld.d <= tp.end_date
  );
$$;

-- Computes whether a room is free or occupied at `p_at`, evaluated in Europe/Bucharest.
-- Mirrors `computeStatus` in `apps/web/features/rooms/server/status.ts`:
--   - unknown room -> ('unknown', null)
--   - outside the teaching periods -> ('unknown', null), never 'free'
--   - rows with parity 'odd' or 'even' only count in teaching weeks of that parity
--   - end_time is exclusive
--   - back-to-back or overlapping classes are merged into one occupied chain
-- Left from TODO-18: admin overrides (backlog #18) and live check-ins are not part of the
-- status; check-ins are shown next to it, never folded into it (CLAUDE.md §4).
create or replace function public.room_status(
  p_room_id text,
  p_at timestamptz
)
returns table (
  status text,
  until text
)
language plpgsql
stable
as $$
declare
  v_local timestamp;
  v_day smallint;
  v_time time;
  v_week integer;
  v_parity text;
  v_until time;
  v_next_until time;
  v_next_start time;
begin
  if not exists (select 1 from public.rooms r where r.id = p_room_id) then
    return query select 'unknown'::text, null::text;
    return;
  end if;

  v_week := public.teaching_week(p_at);
  if v_week is null then
    return query select 'unknown'::text, null::text;
    return;
  end if;
  v_parity := case when v_week % 2 = 1 then 'odd' else 'even' end;

  v_local := p_at at time zone 'Europe/Bucharest';
  v_day := extract(isodow from v_local)::smallint;
  v_time := date_trunc('minute', v_local)::time;

  select max(rs.end_time)
  into v_until
  from public.room_schedule rs
  where rs.room_id = p_room_id
    and rs.day = v_day
    and rs.parity in ('all', v_parity)
    and rs.start_time <= v_time
    and v_time < rs.end_time;

  if v_until is not null then
    loop
      select max(rs.end_time)
      into v_next_until
      from public.room_schedule rs
      where rs.room_id = p_room_id
        and rs.day = v_day
        and rs.parity in ('all', v_parity)
        and rs.start_time <= v_until
        and rs.end_time > v_until;

      exit when v_next_until is null;
      v_until := v_next_until;
    end loop;

    return query select 'occupied'::text, to_char(v_until, 'HH24:MI');
    return;
  end if;

  select min(rs.start_time)
  into v_next_start
  from public.room_schedule rs
  where rs.room_id = p_room_id
    and rs.day = v_day
    and rs.parity in ('all', v_parity)
    and rs.start_time > v_time;

  if v_next_start is not null then
    return query select 'free'::text, to_char(v_next_start, 'HH24:MI');
  else
    return query select 'free'::text, null::text;
  end if;
end;
$$;
